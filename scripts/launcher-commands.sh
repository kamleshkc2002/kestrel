#!/usr/bin/env bash
# Write launcher script commands that run Kestrel actions.
#
#   bash scripts/launcher-commands.sh                 write or refresh them
#   bash scripts/launcher-commands.sh --dir DIR       write to DIR
#   bash scripts/launcher-commands.sh --kestrel PATH  use this kestrel binary
#   bash scripts/launcher-commands.sh --raycast       Raycast directives
#   bash scripts/launcher-commands.sh --uninstall     remove them
#
# The default directory is Vicinae's ($XDG_DATA_HOME/vicinae/scripts/kestrel),
# and the scripts use @vicinae directives with search keywords. --raycast
# writes @raycast directives for other launchers that read Raycast script
# commands (Vicinae reads them too, without the keywords). Each script runs
# `kestrel --command <id>` for an ID from `kestrel --list-commands` and turns
# Kestrel's exit status into a one-line message. Run this again after updating
# Kestrel so new actions appear.

set -euo pipefail

repository="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
app_id="io.github.kamleshkc2002.Kestrel"
marker="# Generated by Kestrel scripts/launcher-commands.sh; rerun it to refresh."
directory="${XDG_DATA_HOME:-$HOME/.local/share}/vicinae/scripts/kestrel"
kestrel=""
uninstall=false
prefix="vicinae"

while [ "$#" -gt 0 ]; do
  case "$1" in
    --dir) directory="${2:?--dir needs a directory}"; shift 2 ;;
    --kestrel) kestrel="${2:?--kestrel needs a path}"; shift 2 ;;
    --raycast) prefix="raycast"; shift ;;
    --uninstall) uninstall=true; shift ;;
    -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "launcher-commands: unknown argument: $1" >&2; exit 2 ;;
  esac
done

# Removes only files this script wrote.
remove_generated() {
  [ -d "$directory" ] || return 0
  local file
  for file in "$directory"/kestrel-*.sh; do
    [ -e "$file" ] || continue
    if grep -qxF "$marker" "$file"; then
      rm -f -- "$file"
    fi
  done
  rm -f -- "$directory/kestrel.svg"
  rmdir --ignore-fail-on-non-empty -- "$directory" 2>/dev/null || true
}

if [ "$uninstall" = true ]; then
  remove_generated
  echo "Removed Kestrel launcher commands from $directory"
  exit 0
fi

if [ -z "$kestrel" ]; then
  kestrel="$(command -v kestrel || true)"
fi
if [ -z "$kestrel" ] || [ ! -x "$kestrel" ]; then
  echo "launcher-commands: kestrel not found; install it or pass --kestrel PATH" >&2
  exit 1
fi
kestrel="$(cd -- "$(dirname -- "$kestrel")" && pwd)/$(basename -- "$kestrel")"

commands="$("$kestrel" --list-commands)"
if [ -z "$commands" ]; then
  echo "launcher-commands: $kestrel listed no commands" >&2
  exit 1
fi

# Quotes a value for a POSIX shell single-quoted string.
quote() {
  printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

remove_generated
mkdir -p -- "$directory"
icon_line=""
if [ -f "$repository/data/icons/$app_id.svg" ]; then
  install -m644 "$repository/data/icons/$app_id.svg" "$directory/kestrel.svg"
  icon_line="# @$prefix.icon kestrel.svg"
fi

count=0
while IFS=$'\t' read -r id description; do
  [ -n "$id" ] || continue
  # Opening Kestrel's own bar from another launcher adds nothing.
  [ "$id" = "command-bar.open" ] && continue
  file="$directory/kestrel-${id//./-}.sh"
  {
    echo "#!/bin/sh"
    echo "# @$prefix.schemaVersion 1"
    echo "# @$prefix.title $description"
    echo "# @$prefix.mode compact"
    echo "# @$prefix.packageName Kestrel"
    [ -z "$icon_line" ] || echo "$icon_line"
    echo "# @$prefix.description Runs kestrel --command $id"
    if [ "$prefix" = "vicinae" ]; then
      echo "# @vicinae.keywords [\"kestrel\", \"$id\"]"
    fi
    echo "$marker"
    echo "$(quote "$kestrel") --command $(quote "$id")"
    echo 'case $? in'
    echo '  0) exit 0 ;;'
    echo "  3) echo \"Turn this feature on in Kestrel's Feature hub\" ;;"
    echo "  4) echo \"Not available on this desktop; Kestrel's window says why\" ;;"
    echo "  5) echo \"On but not running; Kestrel's window says why\" ;;"
    echo "  *) echo \"Kestrel could not run $id\" ;;"
    echo 'esac'
    echo 'exit 1'
  } > "$file"
  chmod 755 "$file"
  count=$((count + 1))
done <<< "$commands"

echo "Wrote $count Kestrel launcher commands to $directory"
